// Write the generated artifacts. Only changed bytes are written, so no tool sees a spurious change.
//   <slotsDir>/gen/<Slot>.jsx   runtime shim (plain ESM in a .jsx file: Vite's optimizer never pre-bundles it)
//   <slotsDir>/gen/<Slot>.d.ts  type shim (go-to-definition lands on the override)
//   <checkFile>                 contract assertions
//   <slotsDir>/gen/check.map.json, state.json
import fs from 'node:fs';
import path from 'node:path';
import { writeIfChanged, relSpec, poisonText, TOOL_NAME } from './util.mjs';

const dtsSpec = (spec) => spec.replace(/\.(tsx|ts|jsx)$/, '.js').replace(/\.mts$/, '.mjs').replace(/\.cts$/, '.cjs');

function directiveFor(p, entry) {
  return p.rsc && entry.kind === 'client' ? `'use client';\n` : '';
}

function reexport(exp, as) {
  return exp === as ? `{ ${as} }` : `{ ${exp} as ${as} }`;
}

/** Shim contents for one slot (null if the slot has no implementation). */
export function shimFor(p, slot) {
  const entry = p.table[slot];
  const impl = entry?.impl;
  if (!impl) return null;
  const as = entry.exportName;
  const dir = p.genDir;
  if (impl.source === 'app') {
    const spec = relSpec(dir, impl.file);
    const target = `${p.rel(impl.file)}#${impl.export}`;
    return {
      js: `${directiveFor(p, entry)}// GENERATED by ${TOOL_NAME}: slot "${slot}" -> ${target}. Do not edit; regenerate: npx ${TOOL_NAME} gen\nexport ${reexport(impl.export, as)} from '${spec}';\n`,
      dts: `// GENERATED by ${TOOL_NAME}: slot "${slot}" -> ${target}\nexport ${reexport(impl.export, as)} from '${dtsSpec(spec)}';\n`,
    };
  }
  const who = impl.source === 'layer' ? `layer ${impl.layer}` : `${p.sdk.name} default`;
  return {
    js: `${directiveFor(p, entry)}// GENERATED by ${TOOL_NAME}: slot "${slot}" -> ${who} (${impl.spec}). Do not edit; regenerate: npx ${TOOL_NAME} gen\nexport ${reexport(impl.export, as)} from '${impl.spec}';\n`,
    dts: `// GENERATED by ${TOOL_NAME}: slot "${slot}" -> ${who}\nexport ${reexport(impl.export, as)} from '${impl.spec}';\n`,
  };
}

function removeStale(p, changed) {
  let ents = [];
  try { ents = fs.readdirSync(p.genDir); } catch { return; }
  for (const f of ents) {
    const m = /^([A-Za-z0-9_]+)\.(jsx|d\.ts)$/.exec(f);
    if (m && !p.sdk.slots[m[1]]) { fs.rmSync(path.join(p.genDir, f), { force: true }); changed.push(path.join(p.genDir, f)); }
  }
}

/** Normal emit: shims, check file, map, state. Returns absolute paths of changed files. */
export function emitAll(p, check) {
  const changed = [];
  const w = (file, content) => { if (writeIfChanged(file, content)) changed.push(file); };
  for (const slot of p.sdk.slotNames) {
    const s = shimFor(p, slot);
    if (!s) continue;
    w(p.shimFile(slot), s.js);
    w(path.join(p.genDir, `${slot}.d.ts`), s.dts);
  }
  removeStale(p, changed);
  w(p.checkFile, check.text);
  w(path.join(p.genDir, 'check.map.json'), JSON.stringify(check.map, null, 2) + '\n');
  w(path.join(p.genDir, 'state.json'), JSON.stringify(p.state, null, 2) + '\n');
  w(path.join(p.genDir, '.gitignore'), '*\n');
  return changed;
}

/**
 * Poison every shim: an import of a relative file whose NAME carries the error. Every dev server reports an
 * unresolvable relative import verbatim (overlay / HTTP 500), with no stunt-double code in the tool.
 */
export function emitPoison(p, problems) {
  const changed = [];
  if (!p.sdk) return changed;
  const text = poisonText(problems.join(' | '));
  for (const slot of p.sdk.slotNames) {
    const as = p.sdk.exportOf(slot);
    const js = `// GENERATED by ${TOOL_NAME}: POISONED because the overrides have errors. Run npx ${TOOL_NAME} check\nimport './STUNT-DOUBLE-ERROR -- ${text} -- run npx ${TOOL_NAME} check';\nexport const ${as} = undefined;\n`;
    if (writeIfChanged(p.shimFile(slot), js)) changed.push(p.shimFile(slot));
  }
  return changed;
}

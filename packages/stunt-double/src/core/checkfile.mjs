// Render <outDir>/check.ts: the contract assertions the type gate runs (and, opted in with `init --editor`, the
// project's own tsc program and IDE). It imports only relative files (the overrides and the generated shims'
// .d.ts), so it compiles in the gate AND in the app program without any tsconfig "paths": the SDK's published
// types never mention the socket package. Shape verified in TS 7.0.2 and 5.9.3, strict on/off:
// passes React.FC / memo / forwardRef / class / children-returning overrides; fails extra-required props,
// narrowed unions, ignored props, wrong ref element, non-components and async client components.
import path from 'node:path';
import { relSpec } from './util.mjs';

const tsSpec = (fromDir, file) => relSpec(fromDir, file).replace(/\.(tsx|ts|jsx|js)$/, '.js').replace(/\.(mts|mjs)$/, '.mjs').replace(/\.(cts|cjs)$/, '.cjs');
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/**
 * @returns {{ text: string, map: { file: string, lines: Record<number, {role, slot?, file?}> } }}
 */
export function renderCheckFile({ sdk, table, checkFile, genDir, overridesDir, layers = [], rel, claimedSlots }) {
  const dir = path.dirname(checkFile);
  const L = [];
  const lines = {};
  const push = (text, info) => { L.push(text); if (info) lines[L.length] = info; };
  push(`// GENERATED by stunt-double from ${sdk.name}@${sdk.version} - do not edit. Regenerate: npx stunt-double gen`);
  push(`/* eslint-disable */`);
  push(`import type { ComponentProps, JSXElementConstructor } from 'react';`);
  push(`import type { SlotProps, SlotName${sdk.abi ? ', SlotAbi' : ''} } from '${sdk.name}/contracts';`);
  push(`export type PropsOf<C> = C extends JSXElementConstructor<any> ? ComponentProps<C> : never;`);
  push(`export type OnlyAsync<C> = C extends (...a: any[]) => infer R ? ([R] extends [PromiseLike<any>] ? true : false) : false;`);
  push('');
  if (sdk.abi) {
    push(`/** [STALE] TS2322 here = the installed ${sdk.name} differs from the one this file was generated for: run \`npx stunt-double gen\` */`);
    push(`export const __abi: SlotAbi = ${q(sdk.abi)};`, { role: 'abi' });
  }
  push(`/** [STALE] TS2305/TS2307 here = a generated shim (${rel(genDir)}/<Slot>.d.ts) is missing or out of date: run \`npx stunt-double gen\` */`);
  for (const s of sdk.slotNames) push(`import { ${sdk.exportOf(s)} as ${s}__wired } from '${relSpec(dir, path.join(genDir, `${s}.js`))}';`, { role: 'wiring', slot: s });
  push(`/** [F2]/[F3] an SDK upgrade added or removed slots: TS1360/TS2353 here until regenerated */`);
  push(`export const __slotSet = { ${sdk.slotNames.map((s) => `${s}: ${s}__wired`).join(', ')} } satisfies Record<SlotName, unknown>;`, { role: 'slotset' });
  const probes = [];
  for (const s of sdk.slotNames) {
    const entry = table[s];
    const impls = (entry?.chain ?? []).filter((c) => c.source !== 'sdk');
    if (!claimedSlots.has(s)) probes.push(s);
    impls.forEach((impl, i) => {
      const id = i === 0 && impl.source === 'app' ? `${s}__impl` : `${s}__L${i}`;
      const label = impl.source === 'app' ? rel(impl.file) : `${impl.spec} (layer ${impl.layer})`;
      const info = { slot: s, file: impl.source === 'app' ? rel(impl.file) : impl.spec };
      const spec = impl.source === 'app' ? tsSpec(dir, impl.file) : impl.spec;
      const ignored = impl.ignoresProps?.length ? impl.ignoresProps.map(q).join(' | ') : 'never';
      push('');
      push(`// ---- slot "${s}" <- ${label}#${impl.export} (${entry.kind}${entry.required ? ', required' : ''})`);
      push(`import { ${impl.export === 'default' ? 'default' : impl.export} as ${id} } from '${spec}';`, { role: 'import', ...info });
      push(`export const ${id}__isComponent: JSXElementConstructor<any> = ${id};`, { role: 'isComponent', ...info });
      push(`export const ${id}__accepts = (p: SlotProps['${s}']): PropsOf<typeof ${id}> => p;`, { role: 'accepts', ...info });
      // inline (no type alias) so tsc prints the evaluated union of missing prop names
      const missing = `Exclude<keyof SlotProps['${s}'], keyof PropsOf<typeof ${id}> | ${ignored}>`;
      push(`export const ${id}__declaresAll: [${missing}] extends [never] ? true`, { role: 'declaresAll', ...info });
      push(`  : { '[F1] override ignores these SDK props': ${missing} } = true;`, { role: 'declaresAll', ...info });
      if (entry.kind === 'client') {
        push(`export const ${id}__notAsync: OnlyAsync<typeof ${id}> extends true`, { role: 'notAsync', ...info });
        push(`  ? { '[F9] client slot override must not be an async component': '${s}' } : true = true;`, { role: 'notAsync', ...info });
      }
    });
  }
  if (probes.length) {
    push('');
    push(`// ---- staleness probes for slots WITHOUT an override when generated (exported, so noUnusedLocals cannot mask them)`);
    for (const s of probes) {
      const spec = relSpec(dir, path.join(overridesDir, s));
      push(`// @ts-expect-error [STALE] no ${rel(overridesDir)}/${s}.* existed when generated; if this stops erroring, run \`npx stunt-double gen\``, { role: 'probe', slot: s });
      push(`export type ${s}__probe = typeof import('${spec}');`, { role: 'probe', slot: s });
    }
  }
  return { text: L.join('\n') + '\n', map: { file: rel(checkFile), lines } };
}

// The type gate: tsc on the generated check program. TypeScript 7 has no classic JS API, so the CLI is
// always spawned, resolved BY PACKAGE NAME (cfg.typescript, so an npm alias like "typescript5" works and a
// second TypeScript's .bin/tsc can never be picked by accident). ANY non-zero exit fails (TS 7: 1, TS 5.9: 2).
import fs from 'node:fs';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { readJson, writeIfChanged, relSpec, findPackageJson, sha, posix } from './util.mjs';
import { readTsconfig } from './tsconfig.mjs';
import { mapDiagnostics, header, formatReport } from './diagnostics.mjs';

export function resolveTypeScript(p) {
  const name = p.cfg.typescript ?? 'typescript';
  const pj = findPackageJson(name, p.root);
  if (!pj) return { error: `[SETUP] the type gate needs the "${name}" package (cfg "typescript"), but it is not installed in ${p.root}: npm i -D ${name === 'typescript' ? 'typescript' : `${name}@npm:typescript@5.9`}` };
  const ts = readJson(pj);
  const binRel = typeof ts.bin === 'string' ? ts.bin : ts.bin?.tsc;
  if (!binRel) return { error: `[SETUP] package "${name}" (${ts.name}@${ts.version}) has no tsc bin.` };
  return { name, version: ts.version, major: Number(String(ts.version).split('.')[0]), bin: path.join(path.dirname(pj), binRel) };
}

/**
 * Write <outDir>/tsconfig.check.json: the gate's OWN tsconfig. It extends the app tsconfig (the referenced app
 * config of a solution-style tsconfig.json), so the overrides compile exactly as in the app (paths, jsx, lib,
 * types, strictness), and its program is the check file only (+ what it imports). The app tsconfig is never
 * modified. No "paths" and no baseUrl (TS 7 rejects baseUrl): the check file imports only relative files.
 */
export function writeCheckTsconfig(p) {
  const file = p.checkTsconfig;
  const dir = path.dirname(file);
  const base = { noEmit: true, skipLibCheck: true, incremental: false, composite: false, noUnusedLocals: false, noUnusedParameters: false, declaration: false, declarationMap: false, emitDeclarationOnly: false, tsBuildInfoFile: null };
  const app = p.tsconfig ? readTsconfig(p.tsconfig) : null;
  // an inherited rootDir that does not contain the outDir would reject the check file (TS6059)
  if (app?.compilerOptions?.rootDir) base.rootDir = relSpec(dir, p.root);
  const files = [relSpec(dir, p.checkFile)];
  const json = p.tsconfig
    ? { extends: relSpec(dir, p.tsconfig), compilerOptions: base, files, include: [] }
    : {
        compilerOptions: { ...base, target: 'es2022', lib: ['es2022', 'dom'], module: 'esnext', moduleResolution: 'bundler', jsx: 'react-jsx', strict: true, allowImportingTsExtensions: true, types: [] },
        files, include: [],
      };
  writeIfChanged(file, `// GENERATED by stunt-double: the contract type gate's tsconfig. Do not edit.\n${JSON.stringify(json, null, 2)}\n`);
  return file;
}

const memo = new Map();

/**
 * NODE_OPTIONS of the tsc child. The parent's are dropped (a test runner's or a loader's hooks must not leak into
 * tsc), except Yarn Plug'n'Play's runtime: without it the child cannot even read tsc from Yarn's zip cache.
 */
function childNodeOptions(root) {
  for (let d = root; ; d = path.dirname(d)) {
    const pnp = path.join(d, '.pnp.cjs');
    if (fs.existsSync(pnp)) return `--require ${JSON.stringify(pnp)}`;
    if (path.dirname(d) === d) return '';
  }
}

/**
 * @returns {Promise<{ ok: boolean, ms?: number, version?: string, message?: string, lines?: string[], output?: string }>}
 */
export function runTypeGate(p, { force = false } = {}) {
  if (p.problems?.length) return Promise.resolve({ ok: false, message: `stunt-double: the type gate did not run because of the injection errors above.`, lines: [] });
  const ts = resolveTypeScript(p);
  if (ts.error) return Promise.resolve({ ok: false, message: formatReport(header(p, 1), [ts.error]), lines: [ts.error] });
  if (p.isPnP && ts.major >= 7) {
    const line = `[TS-PNP] TypeScript ${ts.version} cannot resolve modules under Yarn Plug'n'Play: make typescript@5.9 the project's "typescript" dev dependency (Yarn patches it for PnP; an npm alias such as "typescript5" is NOT patched and cannot resolve either).`;
    return Promise.resolve({ ok: false, message: formatReport(header(p, 1), [line]), lines: [line] });
  }
  const checkText = (() => { try { return fs.readFileSync(p.checkFile, 'utf8'); } catch { return ''; } })();
  // The result depends on the overrides and everything they import, not only on the check file: key the memo
  // on their stamps too, so a dev-time edit re-runs the gate while client + SSR builds share one run.
  const stamps = [...new Set([...(p.implFiles ?? []), ...(p.closureFiles ?? [])])].sort().map((f) => {
    try { const st = fs.statSync(f); return `${f}:${st.mtimeMs}:${st.size}`; } catch { return `${f}:-`; }
  });
  const key = `${p.root}|${p.fingerprint}|${sha(checkText)}|${sha(stamps.join('|'))}|${ts.bin}|${ts.version}`;
  if (!force && memo.has(key)) return memo.get(key);
  const tsconfigFile = writeCheckTsconfig(p);
  const run = new Promise((done) => {
    const t0 = performance.now();
    execFile(process.execPath, [ts.bin, '-p', tsconfigFile, '--pretty', 'false'], { cwd: p.root, maxBuffer: 1 << 26, env: { ...process.env, NODE_OPTIONS: childNodeOptions(p.root) } }, (err, stdout, stderr) => {
      const ms = Math.round(performance.now() - t0);
      const output = `${stdout ?? ''}${stderr ?? ''}`;
      if (!err) return done({ ok: true, ms, version: ts.version, output });
      const map = readJson(p.mapFile);
      let lines = mapDiagnostics(p, output, map);
      if (!lines.length) lines = [`[TS] tsc exited with ${err.code ?? err.signal}: ${output.trim().split('\n').slice(0, 5).join(' | ') || err.message}`];
      const suffix = ` (tsc ${ts.version}, ${ms} ms)`;
      const message = formatReport(header(p, lines.length), lines.map((l, i) => (i === 0 ? l + suffix : l)));
      done({ ok: false, ms, version: ts.version, output, lines, message, tsconfig: posix(path.relative(p.root, tsconfigFile)) });
    });
  });
  memo.set(key, run);
  return run;
}

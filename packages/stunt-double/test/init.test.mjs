test('linksTo: only a link to the slots dir counts; a placeholder tarball or registry range does not', () => {
  const root = '/p';
  assert.equal(linksTo('file:./sdk-slots', root, '/p/sdk-slots'), true);
  assert.equal(linksTo('link:sdk-slots', root, '/p/sdk-slots'), true);
  assert.equal(linksTo('portal:./sdk-slots', root, '/p/sdk-slots'), true);
  assert.equal(linksTo('workspace:*', root, '/p/sdk-slots'), true);
  assert.equal(linksTo('file:../.packs/acme-core-slots-0.0.1.tgz', root, '/p/sdk-slots'), false);
  assert.equal(linksTo('^0.0.1', root, '/p/sdk-slots'), false);
});

// ---- full run on a throwaway project ---------------------------------------------------------------------
function projectWithSdk(files) {
  const tgz = path.join(repo, '.packs', 'acme-core-1.0.0.tgz');
  if (!fs.existsSync(tgz)) throw new Error('run `npm install && npm run setup` at the repository root first (.packs/acme-core-1.0.0.tgz is missing)');
  const d = tmp();
  for (const [rel, text] of Object.entries(files)) write(d, rel, text);
  const sdkDir = path.join(d, 'node_modules', '@acme', 'core');
  fs.mkdirSync(sdkDir, { recursive: true });
  execFileSync('tar', ['xzf', tgz, '-C', sdkDir, '--strip-components=1']);
  return d;
}

function init(root) {
  const lines = [];
  const code = runInit({ root, out: (s) => lines.push(s), err: (s) => lines.push(s) });
  return code.then((c) => ({ code: c, text: lines.join('\n') }));
}

test('runInit: React Router project: app/ layout, placeholder dep replaced, scripts, idempotent second run', async () => {
  const d = projectWithSdk({
    'package.json': JSON.stringify({
      name: 'rr', private: true, type: 'module',
      scripts: { build: 'react-router build', typecheck: 'react-router typegen && tsc' },
      dependencies: { '@acme/core': '^1.0.0', '@acme/core-slots': '^0.0.1', 'react-router': '^8.4.0' },
      devDependencies: { '@react-router/dev': '^8.4.0', typescript: '^5.9.3', vite: '^8.0.3' },
    }, null, 2) + '\n',
    'package-lock.json': '{}',
    'react-router.config.ts': 'export default { ssr: true };\n',
    'vite.config.ts': 'import { reactRouter } from "@react-router/dev/vite";\nimport { defineConfig } from "vite";\n\nexport default defineConfig({\n  plugins: [reactRouter()],\n});\n',
    'tsconfig.json': '{\n  "include": ["**/*", ".react-router/types/**/*"],\n  "compilerOptions": {\n    "rootDirs": [".", "./.react-router/types"],\n    "paths": {\n      "~/*": ["./app/*"]\n    }\n  }\n}\n',
    '.gitignore': '/node_modules/\n',
    'app/root.tsx': 'export default function Root() { return null; }\n',
  });
  const first = await init(d);
  assert.equal(first.code, 0, first.text);
  const cfg = JSON.parse(fs.readFileSync(path.join(d, 'stunt-double.config.json'), 'utf8'));
  assert.deepEqual(cfg, { $schema: './node_modules/@acme/core/stunt-double.schema.json', sdk: '@acme/core', overridesDir: 'app/overrides', checkFile: 'app/stunt-double.check.ts', sourceDirs: ['app'] });
  const pkg = JSON.parse(fs.readFileSync(path.join(d, 'package.json'), 'utf8'));
  assert.equal(pkg.dependencies['@acme/core-slots'], 'file:./sdk-slots');
  assert.equal(pkg.scripts.postinstall, 'stunt-double gen --no-fail');
  assert.equal(pkg.scripts.check, 'stunt-double check');
  assert.equal(pkg.scripts.build, 'react-router build');
  assert.equal(pkg.scripts.typecheck, 'stunt-double check && react-router typegen && tsc');
  assert.equal(pkg.devDependencies.typescript, '^5.9.3');
  assert.match(fs.readFileSync(path.join(d, '.gitignore'), 'utf8'), /^\/node_modules\/\n\n# stunt-double \(generated\)\nsdk-slots\/gen\/\napp\/stunt-double\.check\.ts\n$/);
  const ts = parseJsonc(fs.readFileSync(path.join(d, 'tsconfig.json'), 'utf8'));
  assert.deepEqual(ts.files, ['app/stunt-double.check.ts']);
  assert.deepEqual(Object.keys(ts.compilerOptions.paths), ['@acme/core-slots/*', '~/*']);
  assert.ok(fs.existsSync(path.join(d, 'app/overrides/.gitkeep')));
  assert.ok(fs.existsSync(path.join(d, 'sdk-slots/package.json')));
  assert.match(fs.readFileSync(path.join(d, 'vite.config.ts'), 'utf8'), /plugins: \[stuntDouble\(\), reactRouter\(\)\]/);
  assert.match(first.text, /required slots without an implementation .*Logo \(npx stunt-double eject Logo\)/);

  const snapshot = (dir) => Object.fromEntries(['package.json', 'tsconfig.json', '.gitignore', 'vite.config.ts', 'stunt-double.config.json', 'sdk-slots/package.json'].map((f) => [f, fs.readFileSync(path.join(dir, f), 'utf8')]));
  const before = snapshot(d);
  const second = await init(d);
  assert.equal(second.code, 0);
  assert.equal(second.text, 'stunt-double init: already wired, nothing to change.');
  assert.deepEqual(snapshot(d), before);
});


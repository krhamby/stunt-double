test('runInit: pnpm uses link:, Bun uses workspace:* + workspaces', async () => {
  for (const [lock, want] of [['pnpm-lock.yaml', 'link:./sdk-slots'], ['bun.lock', 'workspace:*']]) {
    const d = projectWithSdk({
      'package.json': JSON.stringify({ name: 'x', dependencies: { '@acme/core': '^1.0.0' }, devDependencies: { typescript: '7.0.2' } }) + '\n',
      [lock]: '',
      'tsconfig.json': '{ "compilerOptions": { "strict": true }, "include": ["src"] }\n',
      'src/main.tsx': '\n',
    });
    const r = await init(d);
    assert.equal(r.code, 0, r.text);
    const pkg = JSON.parse(fs.readFileSync(path.join(d, 'package.json'), 'utf8'));
    assert.equal(pkg.dependencies['@acme/core-slots'], want);
    if (lock === 'bun.lock') assert.deepEqual(pkg.workspaces, ['sdk-slots']);
  }
});


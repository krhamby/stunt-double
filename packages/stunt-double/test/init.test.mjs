// `stunt-double init`: text edits (tsconfig JSONC, vite / astro configs), layout detection, and a full run on a
// throwaway project with the packed @acme/core (needs `npm run setup` at the repository root).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { editTsconfig, editViteConfig, editAstroConfig, addImport, detectLayout, linksTo, runInit } from '../src/init.mjs';
import { parseJsonc } from '../src/core/util.mjs';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'sd-init-'));
const write = (dir, rel, text) => { const f = path.join(dir, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); return f; };

// ---- tsconfig --------------------------------------------------------------------------------------------
const VITE_APP_TSCONFIG = `{
  "compilerOptions": {
    "tsBuildInfoFile": "./node_modules/.tmp/tsconfig.app.tsbuildinfo",
    "target": "es2023",
    /* Bundler mode */
    "moduleResolution": "bundler",
    "jsx": "react-jsx",
    // trailing comma below, as JSONC allows
    "noEmit": true,
  },
  "include": ["src"]
}
`;

test('tsconfig: adds paths + files to a JSONC tsconfig (comments, trailing commas) and is idempotent', () => {
  const d = tmp();
  const f = write(d, 'tsconfig.app.json', VITE_APP_TSCONFIG);
  const r = editTsconfig(f, '@acme/core-slots', './sdk-slots/gen/*', 'src/stunt-double.check.ts');
  assert.equal(r.ok, true);
  assert.deepEqual(r.changes, ['paths "@acme/core-slots/*"', 'files "src/stunt-double.check.ts"']);
  const text = fs.readFileSync(f, 'utf8');
  assert.match(text, /\/\* Bundler mode \*\//);
  assert.match(text, /\/\/ trailing comma below/);
  const json = parseJsonc(text);
  assert.deepEqual(json.compilerOptions.paths, { '@acme/core-slots/*': ['./sdk-slots/gen/*'] });
  assert.deepEqual(json.files, ['src/stunt-double.check.ts']);
  assert.deepEqual(json.include, ['src']);
  const again = editTsconfig(f, '@acme/core-slots', './sdk-slots/gen/*', 'src/stunt-double.check.ts');
  assert.deepEqual(again, { ok: true, changes: [] });
  assert.equal(fs.readFileSync(f, 'utf8'), text);
});

test('tsconfig: merges into existing paths and files (React Router template), ignores look-alikes in comments', () => {
  const d = tmp();
  const f = write(d, 'tsconfig.json', `{
  // "paths": { "not": ["this one"] },
  "include": ["**/*", ".react-router/types/**/*"],
  "files": [],
  "compilerOptions": {
    "rootDirs": [".", "./.react-router/types"],
    "paths": {
      "~/*": ["./app/*"]
    }
  }
}
`);
  const r = editTsconfig(f, '@acme/core-slots', './sdk-slots/gen/*', 'app/stunt-double.check.ts');
  assert.equal(r.ok, true);
  const text = fs.readFileSync(f, 'utf8');
  const json = parseJsonc(text);
  assert.deepEqual(json.compilerOptions.paths, { '@acme/core-slots/*': ['./sdk-slots/gen/*'], '~/*': ['./app/*'] });
  assert.deepEqual(json.files, ['app/stunt-double.check.ts']);
  assert.deepEqual(json.compilerOptions.rootDirs, ['.', './.react-router/types']);
  assert.match(text, /\/\/ "paths": \{ "not": \["this one"\] \},/);
  assert.match(text, /\n {6}"@acme\/core-slots\/\*": \["\.\/sdk-slots\/gen\/\*"\],\n {6}"~\/\*"/);
});


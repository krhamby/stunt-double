// ---- vite / astro configs --------------------------------------------------------------------------------
test('vite.config: Vite react-ts template (no semicolons): import after the last import, plugin first', () => {
  const src = `import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'

// https://vite.dev/config/
export default defineConfig({
  plugins: [react()],
})
`;
  assert.equal(editViteConfig(src), `import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'
import { stuntDouble } from 'stunt-double/vite'

// https://vite.dev/config/
export default defineConfig({
  plugins: [stuntDouble(), react()],
})
`);
});

test('vite.config: React Router template (double quotes, semicolons, several plugins)', () => {
  const src = `import { reactRouter } from "@react-router/dev/vite";
import tailwindcss from "@tailwindcss/vite";
import { defineConfig } from "vite";

export default defineConfig({
  plugins: [tailwindcss(), reactRouter()],
  resolve: {
    tsconfigPaths: true,
  },
});
`;
  const out = editViteConfig(src);
  assert.match(out, /import \{ defineConfig \} from "vite";\nimport \{ stuntDouble \} from "stunt-double\/vite";\n/);
  assert.match(out, /plugins: \[stuntDouble\(\), tailwindcss\(\), reactRouter\(\)\],/);
});

test('vite.config: multi-line imports, no plugins key, a "plugins: [" inside a comment', () => {
  const src = `import {
  defineConfig,
} from 'vite';
// plugins: [old()]
export default defineConfig({
  root: 'web',
});
`;
  const out = editViteConfig(src);
  assert.match(out, /\} from 'vite';\nimport \{ stuntDouble \} from 'stunt-double\/vite';\n/);
  assert.match(out, /\/\/ plugins: \[old\(\)\]\n/);
  assert.match(out, /defineConfig\(\{\n {2}plugins: \[stuntDouble\(\)\],\n {2}root: 'web',/);
});

test('astro.config: no top-level plugins: adds vite.plugins (fresh template, after `astro add react`)', () => {
  const src = `// @ts-check
import { defineConfig } from 'astro/config';

import react from '@astrojs/react';

// https://astro.build/config
export default defineConfig({
  integrations: [react()]
});`;
  const out = editAstroConfig(src);
  assert.match(out, /import react from '@astrojs\/react';\nimport \{ stuntDouble \} from 'stunt-double\/vite';\n/);
  assert.match(out, /defineConfig\(\{\n {2}vite: \{ plugins: \[stuntDouble\(\)\] \},\n {2}integrations: \[react\(\)\]\n\}\);$/);
  assert.equal(editAstroConfig(`import { defineConfig } from 'astro/config';\nexport default defineConfig({});\n`),
    `import { defineConfig } from 'astro/config';\nimport { stuntDouble } from 'stunt-double/vite';\nexport default defineConfig({\n  vite: { plugins: [stuntDouble()] },\n});\n`);
});

test('astro.config: existing vite block, with and without plugins', () => {
  const withPlugins = editAstroConfig(`import { defineConfig } from 'astro/config';\nexport default defineConfig({ integrations: [x()], vite: { plugins: [y()], server: {} } });\n`);
  assert.match(withPlugins, /vite: \{ plugins: \[stuntDouble\(\), y\(\)\], server: \{\} \}/);
  assert.match(withPlugins, /integrations: \[x\(\)\]/);
  const without = editAstroConfig(`import { defineConfig } from 'astro/config';\nexport default defineConfig({ vite: { server: { port: 1 } }, integrations: [z({ plugins: [] })] });\n`);
  assert.match(without, /vite: \{ plugins: \[stuntDouble\(\)\], server: \{ port: 1 \} \}/);
  assert.match(without, /z\(\{ plugins: \[\] \}\)/);
});


// The generated check file (what the type gate compiles) and its line map (how tsc diagnostics are mapped back
// to [Fx] Slot (file) lines).
import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { generate } from '../src/core/index.mjs';
import { project, SRC } from './helpers.mjs';

function generated(files, config) {
  const { root } = project({ files, config });
  const p = generate({ root, onError: 'return' });
  assert.deepEqual(p.problems, []);
  const text = fs.readFileSync(p.checkFile, 'utf8');
  const mapFile = p.mapFile ?? path.join(p.genDir, 'check.map.json');
  const map = JSON.parse(fs.readFileSync(mapFile, 'utf8'));
  const lines = text.split('\n');
  const roleLines = (role, slot) => Object.entries(map.lines).filter(([, v]) => v.role === role && (!slot || v.slot === slot)).map(([n]) => lines[Number(n) - 1]);
  return { p, root, text, map, lines, roleLines };
}

describe('check file', () => {
  const files = { 'src/overrides/Button.tsx': SRC.wrapButton, 'src/overrides/Logo.tsx': SRC.logo, 'src/overrides/Card.tsx': 'export function Card(props) { return props.children; }\n' };

  test('pins the ABI and imports every slot and every override relatively', () => {
    const { p, text } = generated(files);
    assert.match(text, /^\/\/ GENERATED by stunt-double from @acme\/core@1\.0\.0/);
    assert.match(text, new RegExp(`export const __abi: SlotAbi = '${p.sdk.abi.replace(/[.+]/g, '\\$&')}';`));
    assert.match(text, /export const __slotSet = \{ Button: Button__wired, Card: Card__wired, Logo: Logo__wired \} satisfies Record<SlotName, unknown>;/);
    for (const s of ['Button', 'Card', 'Logo']) assert.match(text, new RegExp(`import \\{ ${s} as ${s}__impl \\} from '\\.[./]*/src/overrides/${s}\\.js';`));
  });

  test('five assertions per override; notAsync only for client slots', () => {
    const { roleLines } = generated(files);
    for (const role of ['import', 'isComponent', 'accepts', 'declaresAll']) for (const s of ['Button', 'Card', 'Logo']) assert.ok(roleLines(role, s).length >= 1, `${role} line for ${s}`);
    assert.ok(roleLines('notAsync', 'Button').length >= 1);
    assert.ok(roleLines('notAsync', 'Logo').length >= 1);
    assert.deepEqual(roleLines('notAsync', 'Card'), [], 'Card is a shared slot: async is allowed');
    assert.match(roleLines('accepts', 'Button')[0], /\(p: SlotProps\['Button'\]\): PropsOf<typeof Button__impl> => p/);
    assert.match(roleLines('declaresAll', 'Button').join('\n'), /\[F1\] override ignores these SDK props/);
  });

  test('map.<Slot>.ignoresProps is the reviewable opt-out from declaresAll', () => {
    const { roleLines } = generated(files, { map: { Button: { ignoresProps: ['variant', 'onClick'] } } });
    assert.match(roleLines('declaresAll', 'Button')[0], /'variant' \| 'onClick'/);
    assert.doesNotMatch(roleLines('declaresAll', 'Logo')[0], /'variant'/);
  });

  test('a staleness probe for every slot without an override', () => {
    const { text, roleLines } = generated({ 'src/overrides/Logo.tsx': SRC.logo });
    const probes = roleLines('probe').join('\n');
    assert.match(probes, /@ts-expect-error \[STALE\] no src\/overrides\/Button\.\* existed when generated/);
    assert.match(probes, /export type Button__probe = typeof import\('\.[./]*\/src\/overrides\/Button'\);/);
    assert.match(probes, /Card__probe/);
    assert.doesNotMatch(text, /Logo__probe/);
  });

  test('the map points at real lines of the file it describes', () => {
    const { map, lines, p } = generated(files);
    assert.equal(map.file, p.rel(p.checkFile));
    for (const [n, info] of Object.entries(map.lines)) {
      const line = lines[Number(n) - 1];
      assert.ok(line !== undefined, `map line ${n} exists`);
      if (info.slot && info.role !== 'probe') assert.match(line, new RegExp(info.slot), `line ${n} (${info.role}) mentions ${info.slot}: ${line}`);
    }
  });
});
